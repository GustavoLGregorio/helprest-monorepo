/**
 * patch-android-signing.js
 *
 * Patches android/app/build.gradle and android/app/src/main/res/values/styles.xml
 * after `expo prebuild --clean` to restore:
 *   1. The project keystore (keys/keystore.jks) in the signingConfigs block.
 *   2. The Theme.EdgeToEdge style definition that expo prebuild references but
 *      does not define (normally provided by react-native-edge-to-edge).
 *
 * This script runs automatically after `prebuild:android` and `nuke`.
 */

const fs = require("fs");
const path = require("path");

const BUILD_GRADLE_PATH = path.join(
    __dirname,
    "..",
    "android",
    "app",
    "build.gradle",
);

// Signing config block generated by expo prebuild (target to replace)
const DEFAULT_SIGNING_BLOCK = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }`;

function patchSigning() {
    if (!fs.existsSync(BUILD_GRADLE_PATH)) {
        console.error("[patch-signing] build.gradle not found. Run expo prebuild first.");
        process.exit(1);
    }

    let content = fs.readFileSync(BUILD_GRADLE_PATH, "utf8");
    const keystoreJksPath = path.join(__dirname, "..", "keys", "keystore.jks");
    const hasProjectKeystore = fs.existsSync(keystoreJksPath);

    const projectSigningBlock = `    signingConfigs {
        debug {
            ${hasProjectKeystore ? "storeFile file('../../keys/keystore.jks')\n            storePassword '74bf17c9dd20d10911aa48e1490f8171'\n            keyAlias '0d33bb73fe7a6b8ae839b001b6696f06'\n            keyPassword '619e9a2516524d7d30f3f7b7aa249bde'" : "storeFile file('debug.keystore')\n            storePassword 'android'\n            keyAlias 'androiddebugkey'\n            keyPassword 'android'"}
        }
        release {
            ${hasProjectKeystore ? "storeFile file('../../keys/keystore.jks')\n            storePassword '74bf17c9dd20d10911aa48e1490f8171'\n            keyAlias '0d33bb73fe7a6b8ae839b001b6696f06'\n            keyPassword '619e9a2516524d7d30f3f7b7aa249bde'" : "storeFile file('debug.keystore')\n            storePassword 'android'\n            keyAlias 'androiddebugkey'\n            keyPassword 'android'"}
        }
    }`;

    // Replace signingConfigs block
    content = content.replace(/signingConfigs\s*\{\s*debug\s*\{[\s\S]*?\}\s*\}/, projectSigningBlock);

    // Ensure release buildType references signingConfigs.release
    content = content.replace(/signingConfig signingConfigs\.debug/g, "signingConfig signingConfigs.release");

    fs.writeFileSync(BUILD_GRADLE_PATH, content, "utf8");
    console.log(`[patch-signing] ✅ Patched android/app/build.gradle with ${hasProjectKeystore ? "project keystore.jks" : "debug.keystore"}.`);
}

// ─── Patch 2: styles.xml — define missing Theme.EdgeToEdge ───────────────────

const STYLES_XML_PATH = path.join(
    __dirname,
    "..",
    "android",
    "app",
    "src",
    "main",
    "res",
    "values",
    "styles.xml",
);

const EDGE_TO_EDGE_STYLE = `
  <!--
    Theme.EdgeToEdge: base theme required by Expo's edgeToEdgeEnabled flag.
    Normally provided by react-native-edge-to-edge; defined here directly
    to avoid adding an extra dependency solely for this style definition.
  -->
  <style name="Theme.EdgeToEdge" parent="Theme.AppCompat.DayNight.NoActionBar">
    <item name="android:navigationBarColor">@android:color/transparent</item>
    <item name="android:statusBarColor">@android:color/transparent</item>
    <item name="android:windowTranslucentNavigation">false</item>
    <item name="android:windowTranslucentStatus">false</item>
    <item name="android:windowDrawsSystemBarBackgrounds">true</item>
  </style>`;

function patchStyles() {
    if (!fs.existsSync(STYLES_XML_PATH)) {
        console.warn("[patch-styles] styles.xml not found. Skipping.");
        return;
    }

    let content = fs.readFileSync(STYLES_XML_PATH, "utf8");

    if (content.includes('name="Theme.EdgeToEdge"')) {
        console.log("[patch-styles] ✅ Theme.EdgeToEdge already defined. No patch needed.");
        return;
    }

    // Insert the Theme.EdgeToEdge style right after the <resources ...> opening tag
    content = content.replace(
        /(<resources[^>]*>)/,
        `$1${EDGE_TO_EDGE_STYLE}\n`,
    );

    fs.writeFileSync(STYLES_XML_PATH, content, "utf8");
    console.log("[patch-styles] ✅ Patched styles.xml with Theme.EdgeToEdge definition.");
}

// ─── Patch 3: local.properties — define sdk.dir ─────────────────────────────

const LOCAL_PROPERTIES_PATH = path.join(
    __dirname,
    "..",
    "android",
    "local.properties",
);

function patchLocalProperties() {
    const defaultSdkDir = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || "/home/gustavo/Android/Sdk";
    if (!fs.existsSync(LOCAL_PROPERTIES_PATH)) {
        fs.writeFileSync(LOCAL_PROPERTIES_PATH, `sdk.dir=${defaultSdkDir}\n`, "utf8");
        console.log(`[patch-local-properties] ✅ Created local.properties with sdk.dir=${defaultSdkDir}`);
        return;
    }

    let content = fs.readFileSync(LOCAL_PROPERTIES_PATH, "utf8");
    if (!content.includes("sdk.dir=")) {
        content += `\nsdk.dir=${defaultSdkDir}\n`;
        fs.writeFileSync(LOCAL_PROPERTIES_PATH, content, "utf8");
        console.log(`[patch-local-properties] ✅ Added sdk.dir to local.properties.`);
    }
}

// ─── Run all patches ──────────────────────────────────────────────────────────

patchSigning();
patchStyles();
patchLocalProperties();
